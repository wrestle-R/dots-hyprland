#!/usr/bin/env python3
"""Local shortcut editor for the end-4 settings window. No commands run on save."""

import argparse
import ctypes
import ctypes.util
import fcntl
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
import uuid
from datetime import datetime, timezone

PREFIX = '-- settings-shortcuts-v1: '
LABEL = '[User shortcut] '
HOOK = '-- Local settings shortcuts (managed integration)'
MODS = {'SHIFT': 1, 'CTRL': 4, 'ALT': 8, 'SUPER': 64}


def config_root():
    return Path(os.environ.get('XDG_CONFIG_HOME', str(Path.home() / '.config')))


def shortcut_path():
    return config_root() / 'hypr/custom/settings-shortcuts.lua'


def run(*args):
    result = subprocess.run(args, capture_output=True, text=True, timeout=10)
    if result.returncode:
        raise ValueError(result.stderr.strip() or result.stdout.strip() or f'{args[0]} failed')
    return result.stdout


def lua_string(value):
    # Lua has no JSON-style \u escapes. Encode control characters as decimal escapes.
    return '"' + ''.join('\\' + c if c in '\\"' else f'\\{ord(c):03d}' if ord(c) < 32 or ord(c) == 127 else c for c in value) + '"'


def normalize(chord):
    parts = [p.strip() for p in chord.split('+')]
    aliases = {'CONTROL': 'CTRL', 'WIN': 'SUPER', 'META': 'SUPER'}
    modifiers = [aliases.get(p.upper(), p.upper()) for p in parts[:-1]]
    if not parts[-1] or any(m not in MODS for m in modifiers) or len(set(modifiers)) != len(modifiers):
        raise ValueError('Use a shortcut like SUPER + SHIFT + K, with one final key.')
    key = parts[-1]
    if not re.fullmatch(r'(mouse:[1-9][0-9]*|mouse_(up|down|left|right)|code:[1-9][0-9]*|[A-Za-z0-9_]+)', key):
        raise ValueError('Use a key name such as K, Return, Space, F9 or mouse:275.')
    if not key.startswith(('mouse:', 'mouse_', 'code:')):
        xkb = ctypes.CDLL(ctypes.util.find_library('xkbcommon') or 'libxkbcommon.so.0')
        xkb.xkb_keysym_from_name.argtypes = [ctypes.c_char_p, ctypes.c_int]
        xkb.xkb_keysym_from_name.restype = ctypes.c_uint32
        if not xkb.xkb_keysym_from_name(key.encode(), 1):
            raise ValueError(f'Unknown key name: {key}')
    ordered = [m for m in MODS if m in modifiers]
    return ' + '.join([*ordered, key]), sum(MODS[m] for m in ordered), key.casefold()


def apps():
    import gi
    from gi.repository import Gio
    return sorted([{'id': a.get_id(), 'name': a.get_display_name()} for a in Gio.AppInfo.get_all()
                   if a.get_id() and a.should_show()], key=lambda a: (a['name'].casefold(), a['id']))


def command_for(entry):
    kind, target = entry['kind'], entry['target']
    if kind == 'app':
        if target not in {a['id'] for a in apps()}:
            raise ValueError('That app is no longer installed. Choose another app.')
        return 'gtk-launch ' + shlex.quote(target)
    if kind == 'script':
        path = Path(target).expanduser().resolve()
        if not path.is_file() or not os.access(path, os.X_OK):
            raise ValueError('Choose an existing executable script. New script creates one for you.')
        return shlex.quote(str(path))
    if kind == 'command':
        if not target.strip() or '\x00' in target or len(target) > 8192:
            raise ValueError('Enter a command (maximum 8192 characters).')
        return target
    raise ValueError('Choose App, Command or Script.')


def render(entries):
    lines = [PREFIX + json.dumps(entries, ensure_ascii=False, separators=(',', ':')),
             '-- Generated by Settings > Keybindings. Edit through the tab; keep handwritten bindings in keybinds.lua.']
    for entry in entries:
        lines.append('hl.bind(' + lua_string(entry['chord']) + ', hl.dsp.exec_cmd(' + lua_string(entry['command']) +
                     '), { description = ' + lua_string(LABEL + entry['name']) + ' })')
    return ('\n'.join(lines) + '\n').encode()


def read_entries():
    path = shortcut_path()
    if not path.exists():
        return [], None
    raw = path.read_bytes()
    line = raw.decode().splitlines()[0]
    if not line.startswith(PREFIX):
        raise ValueError('The shortcut file has unrecognized contents; it was left untouched.')
    entries = json.loads(line[len(PREFIX):])
    if not isinstance(entries, list) or render(entries) != raw:
        raise ValueError('The generated shortcut file was edited by hand; it was left untouched.')
    return entries, raw


def active_binds():
    return json.loads(run('hyprctl', '-j', 'binds'))


def identity(bind):
    key = f"code:{bind['keycode']}" if bind.get('keycode') else bind.get('key', '')
    return int(bind.get('modmask', 0)), key.casefold()


def owned(bind, entry):
    return (not bind.get('submap') and identity(bind) == normalize(entry['chord'])[1:]
            and bind.get('description') == LABEL + entry['name'])


def state():
    entries, _ = read_entries()
    rows = []
    for bind in active_binds():
        mask, key = identity(bind)
        modifiers = [name for name, bit in [('SHIFT', 1), ('CAPS', 2), ('CTRL', 4), ('ALT', 8), ('MOD2', 16), ('MOD3', 32), ('SUPER', 64), ('MOD5', 128)] if mask & bit]
        entry = next((e for e in entries if owned(bind, e)), None)
        flags = [name for name in ['release', 'repeat', 'mouse', 'locked', 'longPress', 'non_consuming'] if bind.get(name)]
        rows.append({'chord': ' + '.join([*modifiers, f"code:{bind['keycode']}" if bind.get('keycode') else (bind.get('key') or 'Key not reported')]),
                     'name': bind.get('description') or ('Lua action (no description)' if bind.get('dispatcher') == '__lua' else bind.get('dispatcher', 'Shortcut')),
                     'detail': ('Lua callback' if bind.get('dispatcher') == '__lua' else bind.get('dispatcher', '') + ' ' + bind.get('arg', '')),
                     'submap': bind.get('submap', ''), 'flags': ', '.join(flags), 'entry': entry})
    return {'entries': entries, 'bindings': sorted(rows, key=lambda b: (b['chord'].casefold(), b['name'])), 'apps': apps()}


def atomic(path, data, mode=0o600):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix='.' + path.name, dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def save_backup(raw):
    root = Path(os.environ.get('XDG_STATE_HOME', str(Path.home() / '.local/state'))) / 'hypr-keybinding-backups'
    root.mkdir(parents=True, exist_ok=True, mode=0o700)
    root.chmod(0o700)
    target = root / (datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ-') + uuid.uuid4().hex[:8] + '.lua')
    atomic(target, raw if raw is not None else render([]))
    return str(target)


def change(action, request):
    hook_file = config_root() / 'hypr/custom/keybinds.lua'
    if HOOK not in hook_file.read_text():
        raise ValueError('The settings shortcut integration needs to be installed first.')
    existing_errors = run('hyprctl', 'configerrors').strip()
    if existing_errors:
        raise ValueError('Fix the existing Hyprland configuration errors before saving shortcuts.')
    entries, raw = read_entries()
    old = next((e for e in entries if e['id'] == request.get('id')), None)
    if request.get('id') and old is None:
        raise ValueError('That shortcut was changed elsewhere. Refresh the list.')
    if action == 'delete' and old is None:
        raise ValueError('Choose a custom shortcut to delete.')
    updated = [e for e in entries if e is not old]
    entry = None
    if action == 'save':
        chord, mask, key = normalize(request.get('chord', ''))
        name = request.get('name', '').strip()
        if not name or len(name) > 160 or any(ord(c) < 32 for c in name):
            raise ValueError('Enter a name of 1–160 characters.')
        entry = {'id': old['id'] if old else uuid.uuid4().hex, 'name': name, 'chord': chord,
                 'kind': request.get('kind'), 'target': request.get('target', '').strip()}
        entry['command'] = command_for(entry)
        for bind in active_binds():
            if identity(bind) == (mask, key) and not (old and owned(bind, old)):
                raise ValueError('Shortcut already used: ' + (bind.get('description') or bind.get('dispatcher', 'existing binding')))
        if any(normalize(e['chord'])[1:] == (mask, key) for e in updated):
            raise ValueError('Another saved shortcut already uses those keys.')
        updated.append(entry)
    new = render(updated)
    # Parse generated Lua without running it or launching any command.
    result = subprocess.run(['luac', '-p', '-'], input=new, capture_output=True, timeout=5)
    if result.returncode:
        raise ValueError('Generated Lua did not pass validation; no shortcut was saved.')
    backup = save_backup(raw)
    current = shortcut_path().read_bytes() if shortcut_path().exists() else None
    if current != raw:
        raise ValueError('Shortcuts changed during save. Refresh and try again.')
    try:
        atomic(shortcut_path(), new)
        run('hyprctl', 'reload', 'config-only')
        errors = run('hyprctl', 'configerrors').strip()
        if errors:
            raise ValueError('Hyprland rejected the change.')
        live = active_binds()
        if entry and not any(owned(b, entry) for b in live):
            raise ValueError('Hyprland did not load the shortcut.')
        if old and not entry and any(owned(b, old) for b in live):
            raise ValueError('Hyprland did not remove the shortcut.')
    except Exception as error:
        if raw is None:
            shortcut_path().unlink(missing_ok=True)
        else:
            atomic(shortcut_path(), raw)
        try:
            run('hyprctl', 'reload', 'config-only')
            if run('hyprctl', 'configerrors').strip():
                raise ValueError('Configuration errors remain')
        except Exception:
            raise ValueError(f'Previous file restored; reload needs attention. Backup: {backup}') from error
        raise ValueError(f'Change rolled back: {error}') from error
    return {'message': 'Shortcut saved.' if entry else 'Shortcut removed.', 'backup': backup}


def new_script(request):
    name = request.get('name', '').strip()
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_-]{0,63}\.sh', name):
        raise ValueError('Use a script name like open-work.sh (letters, numbers, hyphens).')
    folder = config_root() / 'hypr/custom/scripts'
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / name
    # Exclusive create: never overwrite an existing file or symlink.
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o700)
    with os.fdopen(fd, 'w') as stream:
        stream.write('#!/usr/bin/env bash\nset -euo pipefail\n\n# Add your commands here, then save this file.\n')
    return {'message': 'Script created. Open it in your editor, then add the shortcut.', 'path': str(path)}


def edit_script(request):
    path = Path(request.get('path', '')).expanduser().resolve()
    if not path.is_file():
        raise ValueError('Choose an existing script to edit.')
    # Open explicitly in a text editor, never through executable-file associations.
    for executable in ['code', 'codium', 'kate', 'gedit', 'mousepad', 'xed']:
        if shutil.which(executable):
            subprocess.Popen([executable, str(path)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                             start_new_session=True, env={k: v for k, v in os.environ.items() if k != 'ELECTRON_RUN_AS_NODE'})
            return {'message': 'Script opened in your editor.'}
    if shutil.which('kitty') and shutil.which('nvim'):
        subprocess.Popen(['kitty', '-e', 'nvim', str(path)], start_new_session=True,
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        return {'message': 'Script opened in your editor.'}
    raise ValueError('No supported text editor found. Open the script manually in your editor.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['list', 'save', 'delete', 'new-script', 'edit-script'])
    parser.add_argument('request', nargs='?', default='{}')
    args = parser.parse_args()
    try:
        lockroot = Path(os.environ.get('XDG_RUNTIME_DIR', str(Path.home() / '.cache'))) / 'hypr-settings-editor'
        lockroot.mkdir(parents=True, exist_ok=True, mode=0o700)
        with (lockroot / 'lock').open('a') as lock:
            fcntl.flock(lock, fcntl.LOCK_EX)
            request = json.loads(args.request)
            result = (state() if args.action == 'list' else new_script(request) if args.action == 'new-script'
                      else edit_script(request) if args.action == 'edit-script' else change(args.action, request))
        print(json.dumps({'ok': True, **result}, ensure_ascii=False))
    except (ValueError, KeyError, TypeError, IndexError, OSError, subprocess.SubprocessError) as error:
        print(json.dumps({'ok': False, 'error': str(error)}))
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
